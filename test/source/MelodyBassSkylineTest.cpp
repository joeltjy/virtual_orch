#include <gtest/gtest.h>

#include <array>
#include <filesystem>

#include <JuceHeader.h>
#include <VirtualOrch/reduction/MelodyBassSkyline.h>

namespace {

auto fixtures() -> juce::var {
    const auto path = std::filesystem::path(VIRTUAL_ORCH_TEST_RESOURCES) / "melody_bass_cases.json";
    return juce::JSON::parse(juce::File(path.string()));
}

auto toSegments(const juce::var &list) -> std::vector<std::array<int, 5>> {
    std::vector<std::array<int, 5>> out;
    for (const auto &row: *list.getArray())
        out.push_back({static_cast<int>(row[0]), static_cast<int>(row[1]), static_cast<int>(row[2]),
                       static_cast<int>(row[3]), static_cast<int>(row[4])});
    return out;
}

auto toArrays(const std::vector<MelodyBass::Segment> &segments) -> std::vector<std::array<int, 5>> {
    std::vector<std::array<int, 5>> out;
    for (const auto &s: segments)
        out.push_back({s.start, s.end, s.pitch, s.velocity, s.sourceIndex});
    return out;
}

} // namespace

namespace virtual_orch_test {

// Cases generated by running the original Python skyline_and_bass (melody_bass.py, version 1)
// on random passages: single notes, repeated-pitch chains, large leaps (troughs), chords.
TEST(MelodyBassSkyline, matchesThePythonReferenceOnRandomPassages) {
    const auto cases = fixtures();
    ASSERT_TRUE(cases.isArray());
    ASSERT_GE(cases.size(), 50);
    int melodyNotes = 0;
    for (int c = 0; c < cases.size(); ++c) {
        std::vector<MelodyBass::Note> notes;
        for (const auto &row: *cases[c]["notes"].getArray())
            notes.push_back({static_cast<int>(row[0]), static_cast<int32_t>(static_cast<int>(row[1])),
                             static_cast<int32_t>(static_cast<int>(row[2])), static_cast<int>(row[3]),
                             static_cast<int>(row[4])});
        const auto result = MelodyBass::skylineAndBass(notes);
        EXPECT_EQ(toArrays(result.melody), toSegments(cases[c]["melody"])) << "melody, case " << c;
        EXPECT_EQ(toArrays(result.bass), toSegments(cases[c]["bass"])) << "bass, case " << c;
        melodyNotes += static_cast<int>(result.melody.size());
    }
    EXPECT_GT(melodyNotes, 100);
}

TEST(MelodyBassSkyline, simpleCases) {
    using MelodyBass::Note;
    // a high line over a low line: melody = high, bass = low
    const auto r = MelodyBass::skylineAndBass(
        {Note{0, 0, 100, 72, 80}, Note{1, 0, 100, 40, 80}});
    ASSERT_EQ(r.melody.size(), 1u);
    EXPECT_EQ(r.melody[0].pitch, 72);
    ASSERT_EQ(r.bass.size(), 1u);
    EXPECT_EQ(r.bass[0].pitch, 40);
    EXPECT_TRUE(MelodyBass::skylineAndBass({}).melody.empty());
}

} // namespace virtual_orch_test
